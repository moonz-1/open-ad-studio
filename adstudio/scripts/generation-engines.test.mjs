import assert from 'node:assert/strict';
import {describeEngines,resolveGenerationEngine} from '../src/generation-engines.ts';
const offline={finish:true,qwen:{available:false,reason:'Missing Qwen weights',missingFiles:['a.safetensors']},reimagine:false,vramFreeBytes:null};
const engines=describeEngines(offline);
assert.equal(engines.find(e=>e.id==='product-safe').available,true);
assert.equal(engines.find(e=>e.id==='qwen').available,false);
assert.equal(engines.find(e=>e.id==='qwen').status,'not-installed');
assert.ok(engines.find(e=>e.id==='flux3'));
assert.ok(engines.find(e=>e.id==='flux3-cloud'));
assert.equal(engines.find(e=>e.id==='flux3').available,false);
assert.equal(engines.find(e=>e.id==='flux3-cloud').available,false);
assert.equal(resolveGenerationEngine('automatic',offline).id,'product-safe');
assert.equal(resolveGenerationEngine('product-safe',offline).preservesOriginalPhotograph,true);
assert.throws(()=>resolveGenerationEngine('qwen',offline),/Qwen Image Edit is not ready|Missing Qwen/);
assert.throws(()=>resolveGenerationEngine('flux3',offline),/FLUX 3/);
const fluxReady={...offline,flux3:{available:true,authorized:true,reason:'FLUX 3 ready'},vramFreeBytes:24*1024**3};
assert.equal(describeEngines(fluxReady).find(e=>e.id==='flux3').available,true);
assert.equal(resolveGenerationEngine('flux3',fluxReady).id,'flux3');
assert.equal(resolveGenerationEngine('automatic',fluxReady).id,'product-safe','Automatic must never silently select FLUX 3');
// Filename presence alone is not enough: unknown VRAM must not unlock AI engines.
const unknownVram={finish:true,qwen:{available:true,reason:'Files present'},reimagine:true,zimage:{available:true,installed:true},vramFreeBytes:null};
assert.equal(resolveGenerationEngine('automatic',unknownVram).id,'product-safe');
assert.equal(describeEngines(unknownVram).find(e=>e.id==='zimage').available,false);
assert.equal(describeEngines(unknownVram).find(e=>e.id==='zimage').status,'insufficient-vram');
assert.throws(()=>resolveGenerationEngine('zimage',unknownVram),/not been verified|admission|Product-safe/);
assert.throws(()=>resolveGenerationEngine('qwen',unknownVram),/not been verified|admission|Product-safe/);
const ready={finish:true,qwen:{available:true,reason:'Ready'},vramFreeBytes:10*1024**3};
assert.equal(resolveGenerationEngine('automatic',ready).id,'qwen');
assert.equal(resolveGenerationEngine('automatic',ready).generatesAiPixels,true);
assert.notEqual(resolveGenerationEngine('automatic',ready).id,'product-safe');
const lowVram={finish:true,qwen:{available:false},reimagine:false,zimage:{available:false,installed:true,reason:'Free/reclaimable VRAM 0.9 GiB is below the 3.5 GiB admission floor for local image generation. Product-safe design remains available.'},vramFreeBytes:900*1024*1024};
assert.equal(describeEngines(lowVram).find(e=>e.id==='zimage').status,'insufficient-vram');
assert.equal(describeEngines(lowVram).find(e=>e.id==='product-safe').available,true);
assert.equal(resolveGenerationEngine('automatic',lowVram).id,'product-safe');
assert.throws(()=>resolveGenerationEngine('zimage',lowVram),/Free|admission|Product-safe|installed but not ready|still-image/i);
const busy={finish:true,qwen:{available:true},reimagine:true,zimage:{available:true,installed:true},vramFreeBytes:12*1024**3,busy:true};
assert.equal(describeEngines(busy).find(e=>e.id==='product-safe').available,true);
assert.equal(resolveGenerationEngine('automatic',busy).id,'product-safe');
assert.equal(describeEngines(busy).find(e=>e.id==='zimage').status,'busy');
console.log('PASS generation engines: product-safe always available, unknown/low VRAM and busy never unlock AI, Automatic falls back without labeling AI.');
